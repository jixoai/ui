#!/usr/bin/env node
// gen-stylex-payload — the compiled-output payload generator
// (stylex-kernel-phase0 P0.4; design §3).
//
// ONE derivation per item through the pinned kernel pipeline (the
// compile core lives in scripts/lib/stylex-payload.mjs — the verify
// gate imports the SAME core, so generator and gate can never disagree
// about what the bytes should be):
//
//   .stylex.ts sources ──▶ @stylexjs/unplugin 0.19.0 transform
//                          (the kernel babel pins, throw mode ON)
//                          ├──▶ classModule  — plain class-string
//                          │                  constants (F11: zero
//                          │                  engine tooling owed)
//                          └──▶ item css     — F9 statement at byte
//                                             zero + the atom rules
//
// Both artifacts carry the same buildId stamp; the manifest records
// sha256s of everything (sources included). Regenerating after a
// source change rewrites every stamp — a partially-updated tree is a
// cross-build mix the gate catches on the stamps.
//
// LANDING SPOT (the decision, receipted): registry/payload/stylex/ —
// OUTSIDE the byte-mirror trees (verify:mirror covers registry/files ⇄
// apps/www/src/lib only; a payload file inside either tree would need
// two-synced-copies for zero benefit), OUTSIDE public/r/ (shadcn build
// owns and regenerates that tree; the phase-1 wiring reads this tree
// when it folds the payload into the shadcn payloads), OUTSIDE the
// registry npm package (registry/ is private @jixoai/www).
//
// Usage (from repo root):
//   node scripts/gen-stylex-payload.mjs          # write the payload tree + manifest
//   node scripts/gen-stylex-payload.mjs --check  # report drift only (verify:stylex-payload is the real gate)

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  artifactBytes,
  artifactPaths,
  derivePayload,
  ENGINE_VERSION,
  GENERATOR_VERSION,
  payloadRoot,
  sha256,
  toPosix,
} from './lib/stylex-payload.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const checkOnly = process.argv.includes('--check');

const { buildId, items } = await derivePayload(root);

const sortedItems = [...items].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
let drift = 0;
const manifest = {
  version: 1,
  note: 'The compiled-output payload manifest (stylex-kernel-phase0 P0.4; spec: css-architecture ADDED "same-build payload consistency"). Every artifact is generated by scripts/gen-stylex-payload.mjs in the SAME pass that writes this manifest; verify:stylex-payload re-derives both artifacts and asserts hash identity, reverse lookup (class constants map to selectors) and the three planted-defect self-tests. Paths are POSIX repo-root-relative.',
  buildId,
  generatorVersion: GENERATOR_VERSION,
  engineVersion: ENGINE_VERSION,
  items: {},
};

for (const [key, derived] of sortedItems) {
  const bytes = artifactBytes(key, buildId, derived);
  const paths = artifactPaths(root, key);
  manifest.items[key] = {
    classModule: { path: toPosix(root, paths.classModule), sha256: sha256(bytes.classModule) },
    css: { path: toPosix(root, paths.css), sha256: sha256(bytes.css) },
    sourceSnapshot: derived.sourceSnapshot,
  };
  if (checkOnly) {
    for (const [file, want] of [
      [paths.classModule, bytes.classModule],
      [paths.css, bytes.css],
    ]) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== want) drift += 1;
    }
  } else {
    mkdirSync(dirname(paths.classModule), { recursive: true });
    writeFileSync(paths.classModule, bytes.classModule);
    writeFileSync(paths.css, bytes.css);
  }
}

if (!checkOnly) {
  // retire item dirs the derivation no longer owns (removed items,
  // renamed corpus modules) — the tree must equal the item set exactly.
  // Only LEAF item dirs retire: a parent (e.g. corpus/) that still
  // carries wanted items underneath stays.
  const wanted = sortedItems.map(([k]) => join(payloadRoot(root), k));
  const isWantedOrAncestor = (dir) => wanted.some((w) => w === dir || w.startsWith(dir + sep));
  if (existsSync(payloadRoot(root))) {
    for (const entry of readdirSync(payloadRoot(root), { withFileTypes: true })) {
      if (entry.isDirectory() && !isWantedOrAncestor(join(payloadRoot(root), entry.name))) {
        rmSync(join(payloadRoot(root), entry.name), { recursive: true, force: true });
        console.log(`[gen:stylex-payload] retired stale item dir: ${entry.name}`);
      }
    }
  }
  writeFileSync(join(payloadRoot(root), 'payload-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  const total = sortedItems.reduce((n, [, v]) => n + (v.classModule.match(/: "/g) ?? []).length, 0);
  console.log(
    `[gen:stylex-payload] ${sortedItems.length} item(s) · buildId ${buildId.slice(0, 12)}… · ${total} class constants · manifest written`,
  );
} else {
  console.log(`[gen:stylex-payload] --check: ${sortedItems.length} item(s) derived, ${drift} drifted artifact(s)`);
  process.exit(drift === 0 ? 0 : 1);
}
